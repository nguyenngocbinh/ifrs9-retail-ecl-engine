SET NOCOUNT ON;
SET XACT_ABORT ON;
/* Synthetic-only input data-quality regression; requires migrations 001..004. */
DECLARE @RUN_ID bigint, @PROCESS_DATE date='20261016', @WRONG_DATE date='20261015';
DECLARE @WEIGHT_VERSION int=2147482991, @ERR int;

BEGIN TRY
 BEGIN TRANSACTION;
 INSERT INTO ecl_cfg.ScenarioWeightVersion(VERSION_ID,VERSION_NAME,EFFECTIVE_FROM,EFFECTIVE_TO,IS_ACTIVE)
 VALUES(@WEIGHT_VERSION,N'Input DQ synthetic regression',@PROCESS_DATE,@PROCESS_DATE,0);
 INSERT INTO ecl_cfg.ScenarioWeight(VERSION_ID,SCENARIO_CODE,SCENARIO_WEIGHT,PROCESS_DATE,IS_ACTIVE)
 VALUES(@WEIGHT_VERSION,'DOWNTURN',0.1568,@PROCESS_DATE,1),
       (@WEIGHT_VERSION,'BASE',0.6864,@PROCESS_DATE,1),
       (@WEIGHT_VERSION,'UPTURN',0.1568,@PROCESS_DATE,1);

 EXEC ecl_core.usp_CreateRun @PROCESS_DATE=@PROCESS_DATE,@RUN_TYPE='FULL',
   @SCENARIO_WEIGHT_VERSION_ID=@WEIGHT_VERSION,@CALCULATION_VERSION='INPUT-DQ-REGRESSION',
   @RUN_ID=@RUN_ID OUTPUT;
 EXEC ecl_core.usp_TransitionRunStatus @RUN_ID=@RUN_ID,@NEW_STATUS='VALIDATING',
   @EVENT_MESSAGE=N'Input data-quality regression';

 INSERT INTO ecl_stg.AccountSnapshot
  (RUN_ID,PROCESS_DATE,ACCOUNT_ID,CUSTOMER_ID,PRODUCT_TYPE,STAGE,POOL_ID,MATURITY_DATE,VERSION_ID,IS_ACTIVE,IS_POCI)
 VALUES(@RUN_ID,@PROCESS_DATE,'SYN-DQ-OK','SYN-CUST-DQ-OK','MORTGAGE',1,'POOL-DQ','20271016',1,1,0),
       (@RUN_ID,@WRONG_DATE,'SYN-DQ-WRONG-DATE','SYN-CUST-DQ-WRONG','MORTGAGE',1,'POOL-DQ','20271016',1,1,0);
 INSERT INTO ecl_stg.PDCurve(RUN_ID,PROCESS_DATE,ACCOUNT_ID,SCENARIO_CODE,FORECAST_PERIOD,MARGINAL_PD,VERSION_ID,IS_ACTIVE)
 VALUES(@RUN_ID,@PROCESS_DATE,'SYN-DQ-OK','DOWNTURN',1,0.03,1,1),
       (@RUN_ID,@PROCESS_DATE,'SYN-DQ-OK','BASE',1,0.02,1,1),
       (@RUN_ID,@PROCESS_DATE,'SYN-DQ-OK','UPTURN',1,0.01,1,1);
 INSERT INTO ecl_stg.LGDCurve(RUN_ID,PROCESS_DATE,ACCOUNT_ID,FORECAST_PERIOD,LGD,VERSION_ID,IS_ACTIVE)
 VALUES(@RUN_ID,@PROCESS_DATE,'SYN-DQ-OK',1,0.4,1,1);
 INSERT INTO ecl_stg.EADCurve(RUN_ID,PROCESS_DATE,ACCOUNT_ID,FORECAST_PERIOD,EAD,CURRENCY_CODE,VERSION_ID,IS_ACTIVE)
 VALUES(@RUN_ID,@PROCESS_DATE,'SYN-DQ-OK',1,1000000,'VND',1,1);
 INSERT INTO ecl_stg.EIRCurve(RUN_ID,PROCESS_DATE,FORECAST_PERIOD,EIR,RATE_BASIS,VERSION_ID,IS_ACTIVE)
 VALUES(@RUN_ID,@PROCESS_DATE,1,0.05,'OTHER',1,1);

 SET @ERR=NULL;
 BEGIN TRY
  INSERT INTO ecl_stg.AccountSnapshot
   (RUN_ID,PROCESS_DATE,ACCOUNT_ID,CUSTOMER_ID,PRODUCT_TYPE,STAGE,POOL_ID,MATURITY_DATE,VERSION_ID,IS_ACTIVE,IS_POCI)
  VALUES(@RUN_ID,@PROCESS_DATE,'SYN-DQ-OK','SYN-CUST-DUP','MORTGAGE',1,'POOL-DQ','20271016',2,1,0);
 END TRY BEGIN CATCH SET @ERR=ERROR_NUMBER(); END CATCH;
 IF @ERR NOT IN(2601,2627) THROW 52400,'Duplicate account grain was not rejected by the canonical key.',1;

 SET @ERR=NULL;
 BEGIN TRY
  INSERT INTO ecl_stg.PDCurve(RUN_ID,PROCESS_DATE,ACCOUNT_ID,SCENARIO_CODE,FORECAST_PERIOD,MARGINAL_PD,VERSION_ID,IS_ACTIVE)
  VALUES(@RUN_ID,@WRONG_DATE,'SYN-DQ-OK','BASE',1,0.025,2,1);
 END TRY BEGIN CATCH SET @ERR=ERROR_NUMBER(); END CATCH;
 IF @ERR NOT IN(2601,2627) THROW 52401,'Duplicate PD grain was not rejected by the canonical key.',1;

 EXEC ecl_core.usp_RegisterRunInput @RUN_ID,'ACCOUNT','TEST','synthetic.account','v1',2,1,NULL;
 EXEC ecl_core.usp_RegisterRunInput @RUN_ID,'PD','TEST','synthetic.pd','v1',3,1,NULL;
 EXEC ecl_core.usp_RegisterRunInput @RUN_ID,'LGD','TEST','synthetic.lgd','v1',1,1,NULL;
 EXEC ecl_core.usp_RegisterRunInput @RUN_ID,'EAD','TEST','synthetic.ead','v1',1,1,NULL;
 EXEC ecl_core.usp_RegisterRunInput @RUN_ID,'EIR','TEST','synthetic.eir','v1',1,1,NULL;
 EXEC ecl_core.usp_RegisterRunInput @RUN_ID,'SCENARIO_WEIGHT','TEST','synthetic.weights','v1',3,1,NULL;
 EXEC ecl_core.usp_SealRunInputs @RUN_ID;
 EXEC ecl_core.usp_ValidateRunInputs @RUN_ID;

 IF NOT EXISTS(SELECT 1 FROM ecl_audit.ValidationError WHERE RUN_ID=@RUN_ID
   AND VALIDATION_CODE='INPUT_PROCESS_DATE_MISMATCH' AND SEVERITY='FATAL'
   AND ACCOUNT_ID='SYN-DQ-WRONG-DATE')
  THROW 52402,'Wrong-date account row was not recorded as a fatal input contract violation.',1;
 IF EXISTS(SELECT 1 FROM ecl_result.ECLDetail WHERE RUN_ID=@RUN_ID)
    OR EXISTS(SELECT 1 FROM ecl_result.ECLAccount WHERE RUN_ID=@RUN_ID)
    OR EXISTS(SELECT 1 FROM ecl_result.ECLPortfolioSummary WHERE RUN_ID=@RUN_ID)
  THROW 52403,'Data-quality validation must not generate ECL output rows.',1;

 ROLLBACK TRANSACTION;
 PRINT 'PASS: wrong reporting date is fatal; duplicate account and PD grains are rejected; no ECL outputs.';
END TRY
BEGIN CATCH
 IF XACT_STATE()<>0 ROLLBACK TRANSACTION;
 THROW;
END CATCH;
