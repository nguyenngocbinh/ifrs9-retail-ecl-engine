-- DB2 LUW: calculate Non-Revolving EAD by contractual principal schedule.
-- Writes results to RM_RDM_MOP_PROD.TBL_NONREVOLVING_EAD_SCHEDULE.
-- P_SEGMENT restricts processing to a single product-modelling segment.
-- Product mapping: FCC_RPTB_CL020.PRODUCT = PRODUCT_CODE_IFRS9.PRODUCT_CODE.
--
--#SET TERMINATOR @

CREATE OR REPLACE PROCEDURE RM_RDM_MOP_PROD.SP_CALC_NONREVOLVING_EAD
(
    IN P_PROCESS_DATE DATE,
    IN P_SEGMENT      VARCHAR(50)
)
LANGUAGE SQL
MODIFIES SQL DATA
BEGIN

    IF P_SEGMENT IS NULL OR TRIM(P_SEGMENT) = '' THEN
        SIGNAL SQLSTATE '75001'
            SET MESSAGE_TEXT = 'P_SEGMENT is required (for example Mortgage or Autoloan).';
    END IF;

    -- Delete only rows for the requested segment so a run for another segment
    -- on the same process date is preserved.
    DELETE FROM RM_RDM_MOP_PROD.TBL_NONREVOLVING_EAD_SCHEDULE T
    WHERE T.PROCESS_DATE = P_PROCESS_DATE
      AND EXISTS
      (
          SELECT 1
          FROM TPBCSO_SEC.FCC_RPTB_CL020 R
          INNER JOIN RM_RDM_MOP_PROD.PRODUCT_CODE_IFRS9 P
              ON P.PRODUCT_CODE = R.PRODUCT
          WHERE R.CONTRACT_REF_NO = T.ACCOUNT_NUMBER
            AND DATE(R.BACKUP_DATE) = P_PROCESS_DATE
            AND P.PRODUCT_MODELLING = P_SEGMENT
      );

    INSERT INTO RM_RDM_MOP_PROD.TBL_NONREVOLVING_EAD_SCHEDULE
    (
        PROCESS_DATE,
        ACCOUNT_NUMBER,
        MATURITY_DATE,
        SCHEDULE_DUE_DATE,
        SCHEDULE_NO,
        EAD_0,
        PRINCIPAL_REPAYMENT,
        CUM_PRINCIPAL_REPAYMENT,
        EAD_AFTER_REPAYMENT
    )
    WITH BASE_EAD AS
    (
        SELECT
            R.CONTRACT_REF_NO AS ACCOUNT_NUMBER,
            P_PROCESS_DATE AS PROCESS_DATE,
            R.OUTSTANDINGVND AS EAD_0,
            DATE(R.MATURITY_DATE) AS MATURITY_DATE
        FROM TPBCSO_SEC.FCC_RPTB_CL020 R
        INNER JOIN RM_RDM_MOP_PROD.PRODUCT_CODE_IFRS9 P
            ON P.PRODUCT_CODE = R.PRODUCT
        WHERE DATE(R.BACKUP_DATE) = P_PROCESS_DATE
          AND P.PRODUCT_MODELLING = P_SEGMENT
    ),
    FUTURE_SCHEDULE AS
    (
        SELECT
            B.PROCESS_DATE,
            B.ACCOUNT_NUMBER,
            B.EAD_0,
            B.MATURITY_DATE,
            CASE
                WHEN F.SCHEDULE_DUE_DATE IS NULL THEN B.PROCESS_DATE
                ELSE DATE(F.SCHEDULE_DUE_DATE)
            END AS SCHEDULE_DUE_DATE,
            CASE
                WHEN F.SCHEDULE_DUE_DATE IS NULL THEN 0
                ELSE F.SCHEDULE_NO
            END AS SCHEDULE_NO,
            CASE
                WHEN F.SCHEDULE_DUE_DATE IS NULL THEN 0
                ELSE F.AMOUNT_DUE
            END AS PRINCIPAL_REPAYMENT
        FROM BASE_EAD B
        LEFT JOIN TPBCSO_SEC.FCC_LOAN_SCHEDULE F
            ON F.ACCOUNT_NUMBER = B.ACCOUNT_NUMBER
           AND F.COMPONENT_NAME = 'PRINCIPAL'
           AND DATE(F.SCHEDULE_DUE_DATE) > P_PROCESS_DATE
    ),
    CUMULATIVE_EAD AS
    (
        SELECT
            S.*,
            SUM(COALESCE(S.PRINCIPAL_REPAYMENT, 0)) OVER
            (
                PARTITION BY S.ACCOUNT_NUMBER
                ORDER BY S.SCHEDULE_DUE_DATE, S.SCHEDULE_NO
                ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
            ) AS CUM_PRINCIPAL_REPAYMENT
        FROM FUTURE_SCHEDULE S
    )
    SELECT
        PROCESS_DATE,
        ACCOUNT_NUMBER,
        MATURITY_DATE,
        SCHEDULE_DUE_DATE,
        SCHEDULE_NO,
        EAD_0,
        PRINCIPAL_REPAYMENT,
        CUM_PRINCIPAL_REPAYMENT,
        CASE
            WHEN EAD_0 - CUM_PRINCIPAL_REPAYMENT < 0 THEN 0
            ELSE EAD_0 - CUM_PRINCIPAL_REPAYMENT
        END AS EAD_AFTER_REPAYMENT
    FROM CUMULATIVE_EAD;

END
@

--#SET TERMINATOR ;

