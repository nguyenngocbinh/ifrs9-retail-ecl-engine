-- DB2 LUW: calculate Non-Revolving EAD by contractual principal schedule.
-- Writes results to RM_RDM_MOP_PROD.TBL_NONREVOLVING_EAD_SCHEDULE.
-- This initial implementation uses the source fields and assumptions documented in README.
--
--#SET TERMINATOR @

CREATE PROCEDURE RM_RDM_MOP_PROD.SP_CALC_NONREVOLVING_EAD
(
    IN P_PROCESS_DATE DATE
)
LANGUAGE SQL
MODIFIES SQL DATA
BEGIN

    DELETE FROM RM_RDM_MOP_PROD.TBL_NONREVOLVING_EAD_SCHEDULE
    WHERE PROCESS_DATE = P_PROCESS_DATE;

    INSERT INTO RM_RDM_MOP_PROD.TBL_NONREVOLVING_EAD_SCHEDULE
    (
        PROCESS_DATE,
        ACCOUNT_NUMBER,
        MATURITY_DATE,
        SCHEDULE_DUE_DATE,
        SCHEDULE_NO,
        EAD_0,
        PRINCIPAL_REPAYMENT,
        CUM_PRINCIPAL_REPAYMENT,
        EAD_AFTER_REPAYMENT
    )
    WITH BASE_EAD AS
    (
        SELECT
            R.CONTRACT_REF_NO AS ACCOUNT_NUMBER,
            P_PROCESS_DATE AS PROCESS_DATE,
            R.OUTSTANDINGVND AS EAD_0,
            DATE(R.MATURITY_DATE) AS MATURITY_DATE
        FROM TPBCSO_SEC.FCC_RPTB_CL020 R
        WHERE DATE(R.BACKUP_DATE) = P_PROCESS_DATE
    ),
    FUTURE_SCHEDULE AS
    (
        SELECT
            B.PROCESS_DATE,
            B.ACCOUNT_NUMBER,
            B.EAD_0,
            B.MATURITY_DATE,
            CASE
                WHEN F.SCHEDULE_DUE_DATE IS NULL THEN B.PROCESS_DATE
                ELSE DATE(F.SCHEDULE_DUE_DATE)
            END AS SCHEDULE_DUE_DATE,
            CASE
                WHEN F.SCHEDULE_DUE_DATE IS NULL THEN 0
                ELSE F.SCHEDULE_NO
            END AS SCHEDULE_NO,
            CASE
                WHEN F.SCHEDULE_DUE_DATE IS NULL THEN 0
                ELSE F.AMOUNT_DUE
            END AS PRINCIPAL_REPAYMENT
        FROM BASE_EAD B
        LEFT JOIN TPBCSO_SEC.FCC_LOAN_SCHEDULE F
            ON F.ACCOUNT_NUMBER = B.ACCOUNT_NUMBER
           AND F.COMPONENT_NAME = 'PRINCIPAL'
           AND DATE(F.SCHEDULE_DUE_DATE) > P_PROCESS_DATE
    ),
    CUMULATIVE_EAD AS
    (
        SELECT
            S.*,
            SUM(COALESCE(S.PRINCIPAL_REPAYMENT, 0)) OVER
            (
                PARTITION BY S.ACCOUNT_NUMBER
                ORDER BY S.SCHEDULE_DUE_DATE, S.SCHEDULE_NO
                ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
            ) AS CUM_PRINCIPAL_REPAYMENT
        FROM FUTURE_SCHEDULE S
    )
    SELECT
        PROCESS_DATE,
        ACCOUNT_NUMBER,
        MATURITY_DATE,
        SCHEDULE_DUE_DATE,
        SCHEDULE_NO,
        EAD_0,
        PRINCIPAL_REPAYMENT,
        CUM_PRINCIPAL_REPAYMENT,
        CASE
            WHEN EAD_0 - CUM_PRINCIPAL_REPAYMENT < 0 THEN 0
            ELSE EAD_0 - CUM_PRINCIPAL_REPAYMENT
        END AS EAD_AFTER_REPAYMENT
    FROM CUMULATIVE_EAD;

END
@

--#SET TERMINATOR ;

